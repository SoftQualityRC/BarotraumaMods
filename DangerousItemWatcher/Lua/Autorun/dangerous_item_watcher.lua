local function trim(s)
    return (s:gsub("^%s+", ""):gsub("%s+$", ""))
end

local function notifyHost(text)
    local ok, err = pcall(function()
        for _, client in pairs(Client.ClientList) do
            if client.IsOwner then
                Game.SendDirectChatMessage(
                    "DangerousItemWatcher",
                    text,
                    nil,
                    ChatMessageType.MessageBox,
                    client
                )
                return
            end
        end

        print(TAG .. " Хост не найден. " .. text)
    end)

    if not ok then
        print(TAG .. " Ошибка отправки: " .. tostring(err))
        print(TAG .. " " .. text)
    end
end

local function report(player, action, rawItem)
    rawItem = trim(rawItem)

    local amount, itemName = rawItem:match("^x(%d+)%s+(.+)$")
    amount = tonumber(amount) or 1
    itemName = itemName or rawItem

    local label = WATCHED[itemName]
    if not label then return end

    local suffix = amount > 1 and (" x" .. amount) or ""
    local message = player .. " " .. action .. " " .. label .. suffix

    notifyHost(message)
    print(TAG .. " " .. message)
end

Hook.Add("serverLog", "DangerousItemWatcher.ServerLog", function(line, messageType)
    if not SERVER or type(line) ~= "string" then return end

    local player, item = line:match("^(.-) picked up (.+)$")
    if player and item then
        report(player, "взял", item)
        return
    end

    player, item = line:match(
        "^(.-) placed (.-) in the inventory of .+$"
    )
    if player and item then
        report(player, "положил", item)
        return
    end

    player, item = line:match("^(.-) dropped (.+)$")
    if player and item then
        report(player, "выбросил", item)
    end
	
	-- Игрок забрал предмет из контейнера
	local player, item = line:match(
		"^(.-) removed (.-) from the inventory of .+$"
	)

	if player and item then
		report(player, "взял", item)
        return
    end
end)

